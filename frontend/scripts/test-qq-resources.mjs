import assert from 'node:assert/strict';
import { createModuleLoader, mockModule, sourceUrl } from './module-loader.mjs';

const calls = [];
const load = createModuleLoader({ [sourceUrl('api/http.ts')]: mockModule({ request: async (url, options) => { calls.push({ url, options }); return {}; } }) });
const { readResourceQuery, resourceQueryUrl, resourcePages } = (await load('../src/components/projects/qqResources.ts')).exports;
const { isResourcesRoute, readProjectRoute } = (await load('../src/components/projects/navigation.ts')).exports;
const defaults = { page: 1, sort: 'created_at', order: 'desc', favorite: 'all' };
assert.deepEqual(readResourceQuery(''), defaults);
assert.deepEqual(readResourceQuery('?page=-2&sort=bad&order=bad&favorite=bad'), defaults);
assert.deepEqual(readResourceQuery('?page=1.5'), defaults);
const chosen = { page: 3, sort: 'size', order: 'asc', favorite: 'favorites' };
const route = new URL(resourceQueryUrl('project/id', chosen), 'http://localhost');
assert.equal(route.pathname, '/projects/project%2Fid/resources');
assert.deepEqual(readResourceQuery(route.search), chosen);
assert.equal(isResourcesRoute(route), true);
assert.deepEqual(readProjectRoute(route), { projectId: 'project/id', sessionId: null });
assert.deepEqual(readProjectRoute({ pathname: '/projects/p/resources', search: '?session=wrong' }), { projectId: 'p', sessionId: null });
assert.equal(isResourcesRoute({ pathname: '/projects/p' }), false);
assert.deepEqual(resourcePages(1, 1), [1]);
assert.deepEqual(resourcePages(5, 12), [1, 'ellipsis', 4, 5, 6, 'ellipsis', 12]);
assert.deepEqual(resourcePages(12, 12), [1, 'ellipsis', 11, 12]);
const { qqResourcesApi } = (await load('../src/api/qq.ts')).exports;
await qqResourcesApi.list(chosen);
const requested = new URL(calls.at(-1).url, 'http://localhost');
assert.deepEqual(readResourceQuery(requested.search), chosen);
assert.equal(requested.searchParams.get('page_size'), '30');
await qqResourcesApi.update(7, { description: '' });
assert.equal(calls.at(-1).url, '/api/qq/resources/7');
assert.deepEqual(JSON.parse(calls.at(-1).options.body), { description: '' });
await qqResourcesApi.update(7, { is_favorite: false });
assert.deepEqual(JSON.parse(calls.at(-1).options.body), { is_favorite: false });
await qqResourcesApi.remove(7);
assert.equal(calls.at(-1).options.method, 'DELETE');
console.log('QQ resource navigation, pagination and API contracts passed.');
